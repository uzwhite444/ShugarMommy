-- ------------------------------------------------------------
-- 1. Предохранитель: не закрывать дверь, пока не открыта новая
-- ------------------------------------------------------------

do $$
declare
  fn_exists boolean;
  via_function integer;
begin
  fn_exists := to_regprocedure(
    'public.create_booking(uuid, text, text, text, text, date, text, text[], text, text)'
  ) is not null;

  if not fn_exists then
    raise exception
      'Сначала выполните 12_server_pricing.sql — функции create_booking() ещё нет. Если закрыть вставку сейчас, сайт не сможет сохранить ни одной заявки.';
  end if;

  -- zone_ids заполняет только create_booking(). Ни одной такой записи —
  -- значит новый сайт ещё не выложен или через него ещё не записывались.
  select count(*) into via_function from public.bookings where zone_ids is not null;

  if via_function = 0 then
    raise exception
      'Ни одной заявки через create_booking() пока нет. Выложите новый сайт, сделайте на нём пробную запись (она появится в админке) и выполните этот файл снова. Если вы точно знаете, что делаете, выполните два оператора из раздела 2 вручную.';
  end if;
end $$;

-- ------------------------------------------------------------
-- 2. Закрыть прямую вставку
--
-- Политика позволяла anon вставить строку с любым total_price: RLS проверял
-- только status = 'new'. Пока она существует, сервер может считать цену
-- сколько угодно правильно — рядом остаётся дверь, где её приносит клиент.
--
-- create_booking() продолжает работать: она SECURITY DEFINER и выполняется
-- от владельца таблицы, на которого RLS не действует.
-- ------------------------------------------------------------

drop policy if exists "anon can insert bookings" on public.bookings;
revoke insert on public.bookings from anon;

notify pgrst, 'reload schema';

